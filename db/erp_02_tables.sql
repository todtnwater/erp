-- Run as ERP user, connected to XEPDB1
CREATE TABLE erp_product (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR2(30 CHAR)  NOT NULL,
  name             VARCHAR2(100 CHAR) NOT NULL,
  category         VARCHAR2(50 CHAR),
  origin           VARCHAR2(30 CHAR),
  unit             VARCHAR2(20 CHAR),
  kg_per_box       NUMBER(5) NOT NULL,
  boxes_per_pallet NUMBER(5) NOT NULL,
  description      VARCHAR2(300 CHAR),
  stock_qty        NUMBER(10) DEFAULT 0 NOT NULL,
  safety_qty       NUMBER(10) DEFAULT 0 NOT NULL,
  location         VARCHAR2(30 CHAR),
  updated_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_erp_product_code UNIQUE (code),
  CONSTRAINT ck_erp_product_stock CHECK (stock_qty >= 0),
  CONSTRAINT ck_erp_product_safety CHECK (safety_qty >= 0),
  CONSTRAINT ck_erp_product_kg CHECK (kg_per_box > 0),
  CONSTRAINT ck_erp_product_bpp CHECK (boxes_per_pallet > 0)
);

CREATE TABLE erp_inbound_plan (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_date      DATE NOT NULL,
  product_id     NUMBER NOT NULL,
  planned_qty    NUMBER(10) NOT NULL,
  received_qty   NUMBER(10) DEFAULT 0 NOT NULL,
  source         VARCHAR2(30 CHAR),
  updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_erp_plan_product FOREIGN KEY (product_id) REFERENCES erp_product(id),
  CONSTRAINT uq_erp_plan UNIQUE (plan_date, product_id),
  CONSTRAINT ck_erp_plan_qty CHECK (planned_qty > 0 AND received_qty >= 0)
);

CREATE TABLE erp_stock_tx (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  NUMBER NOT NULL,
  plan_id     NUMBER,
  tx_type     VARCHAR2(10) NOT NULL,
  qty         NUMBER(10) NOT NULL,
  before_qty  NUMBER(10) NOT NULL,
  after_qty   NUMBER(10) NOT NULL,
  actor       VARCHAR2(50 CHAR),
  channel     VARCHAR2(10) NOT NULL,
  reason_code VARCHAR2(30),
  memo        VARCHAR2(300 CHAR),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_erp_tx_product FOREIGN KEY (product_id) REFERENCES erp_product(id),
  CONSTRAINT fk_erp_tx_plan FOREIGN KEY (plan_id) REFERENCES erp_inbound_plan(id),
  CONSTRAINT ck_erp_tx_type CHECK (tx_type IN ('IN', 'OUT')),
  CONSTRAINT ck_erp_tx_qty CHECK (qty > 0),
  CONSTRAINT ck_erp_tx_channel CHECK (channel IN ('UI', 'AI'))
);

CREATE INDEX ix_erp_tx_created ON erp_stock_tx (created_at);

CREATE TABLE erp_pending_action (
  id             VARCHAR2(36) PRIMARY KEY,
  action_type    VARCHAR2(10) NOT NULL,
  product_id     NUMBER NOT NULL,
  plan_id        NUMBER,
  qty            NUMBER(10) NOT NULL,
  before_qty     NUMBER(10) NOT NULL,
  after_qty      NUMBER(10) NOT NULL,
  exception_flag NUMBER(1) DEFAULT 0 NOT NULL,
  warning        VARCHAR2(1000 CHAR),
  actor          VARCHAR2(50 CHAR),
  status         VARCHAR2(10) NOT NULL,
  memo           VARCHAR2(300 CHAR),
  created_at     TIMESTAMP NOT NULL,
  expires_at     TIMESTAMP NOT NULL,
  decided_at     TIMESTAMP,
  CONSTRAINT fk_erp_pa_product FOREIGN KEY (product_id) REFERENCES erp_product(id),
  CONSTRAINT ck_erp_pa_type CHECK (action_type IN ('IN', 'OUT')),
  CONSTRAINT ck_erp_pa_status CHECK (status IN ('PENDING', 'DONE', 'REJECTED')),
  CONSTRAINT ck_erp_pa_flag CHECK (exception_flag IN (0, 1))
);
