package com.ssk.erp.config;

import com.ssk.erp.dao.UserDAO;
import com.ssk.erp.dto.UserDTO;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * 1) erp_user 테이블이 없으면 만든다 (sqlplus 없이 바로 쓰도록)
 * 2) 사용자가 한 명도 없으면 초기 계정 2개를 만든다
 *    - admin (관리자, is_admin = 1) / staff (현장 직원, is_admin = 0)
 *    - 비밀번호는 /etc/erp.properties 의 erp.seed.admin-password, erp.seed.staff-password
 *      비어 있으면 임의 비밀번호를 만들어 로그(~/erp.log)에 한 번만 출력
 */
@Component
@Order(0)
public class UserSeeder implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(UserSeeder.class);

    private static final String CREATE_TABLE = """
            CREATE TABLE erp_user (
              id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              login_id       VARCHAR2(30 CHAR)  NOT NULL,
              password_hash  VARCHAR2(200 CHAR) NOT NULL,
              name           VARCHAR2(30 CHAR)  NOT NULL,
              is_admin       NUMBER(1) DEFAULT 0 NOT NULL,
              enabled        NUMBER(1) DEFAULT 1 NOT NULL,
              created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
              last_login_at  TIMESTAMP,
              CONSTRAINT uq_erp_user_login UNIQUE (login_id),
              CONSTRAINT ck_erp_user_admin CHECK (is_admin IN (0, 1)),
              CONSTRAINT ck_erp_user_enabled CHECK (enabled IN (0, 1))
            )""";

    private final JdbcTemplate jdbc;
    private final UserDAO userDAO;
    private final String adminPassword;
    private final String staffPassword;

    public UserSeeder(JdbcTemplate jdbc, UserDAO userDAO,
                      @Value("${erp.seed.admin-password:}") String adminPassword,
                      @Value("${erp.seed.staff-password:}") String staffPassword) {
        this.jdbc = jdbc;
        this.userDAO = userDAO;
        this.adminPassword = adminPassword == null ? "" : adminPassword.trim();
        this.staffPassword = staffPassword == null ? "" : staffPassword.trim();
    }

    @Override
    public void run(String... args) {
        Integer exists = jdbc.queryForObject(
                "SELECT COUNT(*) FROM user_tables WHERE table_name = 'ERP_USER'", Integer.class);
        if (exists == null || exists == 0) {
            jdbc.execute(CREATE_TABLE);
            log.info("erp_user 테이블을 만들었습니다.");
        }
        if (userDAO.count() > 0) {
            return;
        }
        String adminPw = adminPassword.length() >= 8 ? adminPassword : PasswordHasher.randomPassword(12);
        String staffPw = staffPassword.length() >= 8 ? staffPassword : PasswordHasher.randomPassword(12);
        userDAO.insert(new UserDTO("admin", PasswordHasher.hash(adminPw), "관리자", 1));
        userDAO.insert(new UserDTO("staff", PasswordHasher.hash(staffPw), "현장직원", 0));
        if (adminPassword.length() < 8 || staffPassword.length() < 8) {
            log.warn("==== 초기 계정 생성 (이 로그는 다시 안 나옵니다. 비밀번호를 바로 적어 두세요) ====");
            if (adminPassword.length() < 8) {
                log.warn("관리자  아이디 admin / 비밀번호 {}", adminPw);
            }
            if (staffPassword.length() < 8) {
                log.warn("현장직원 아이디 staff / 비밀번호 {}", staffPw);
            }
        } else {
            log.info("초기 계정 admin(관리자), staff(현장직원)을 /etc/erp.properties 비밀번호로 만들었습니다.");
        }
    }
}
